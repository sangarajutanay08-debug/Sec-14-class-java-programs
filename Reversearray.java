public class Reversearray {
    public static void main(String[] args) {

        int[] arr = {10, 20, 30, 40, 50};

        System.out.println("Start of the Array elements: ");

        for (int i = 4; i >= 0; i--) {
            System.out.println(arr[i]);
        }
        System.out.println("End of the Array ");
    }
}

